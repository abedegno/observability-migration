"""Bounded Zstandard frame-integrity preflight, without an external CLI.

Only published container framing is read here (RFC 8878 sections 3.1.1/3.1.2).
The existing zstandard library owns header interpretation, block decompression,
checksums and EOF validation. Feeding at most one 128 KiB block prevents the
incremental API from collecting an entire decompressed frame in one return.
No proprietary journal bytes are interpreted or generated by this module.
"""
import zstandard

MAGIC=b'\x28\xb5\x2f\xfd'
MAX_WINDOW_BYTES=32*1024**2
BLOCK_BYTES=128*1024


class FrameIntegrityError(ValueError):pass


def is_zstd_magic(value):
    return len(value)==4 and (value==MAGIC or 0x184d2a50<=int.from_bytes(value,'little')<=0x184d2a5f)


def _read(file,size):
    chunks=[];left=size
    while left:
        value=file.read(left)
        if not value:raise FrameIntegrityError('truncated Zstd frame')
        chunks.append(value);left-=len(value)
    return b''.join(chunks)


def preflight(file,*,max_output_bytes=None):
    if max_output_bytes is not None and (type(max_output_bytes) is not int or max_output_bytes<0):raise FrameIntegrityError('invalid decompressed byte limit')
    frames=skips=blocks=total=checksums=max_window=max_chunk=0
    def account(value):
        nonlocal total,max_chunk
        max_chunk=max(max_chunk,len(value));total+=len(value)
        if max_output_bytes is not None and total>max_output_bytes:raise FrameIntegrityError('decompressed byte limit exceeded during Zstd integrity preflight')
    try:
        while True:
            magic=file.read(4)
            if not magic:break
            if len(magic)!=4:magic+=_read(file,4-len(magic))
            number=int.from_bytes(magic,'little')
            if 0x184d2a50<=number<=0x184d2a5f:
                length=int.from_bytes(_read(file,4),'little');skips+=1
                while length:
                    amount=min(length,BLOCK_BYTES);_read(file,amount);length-=amount
                continue
            if magic!=MAGIC:raise FrameIntegrityError('unrecognized bytes after Zstd frame')
            prefix=magic+_read(file,1);size=zstandard.frame_header_size(prefix)
            if not 5<=size<=18:raise FrameIntegrityError('unsupported Zstd frame header size')
            header=prefix+_read(file,size-5);params=zstandard.get_frame_parameters(header)
            if params.window_size>MAX_WINDOW_BYTES:raise FrameIntegrityError('Zstd window exceeds 32 MiB bound')
            max_window=max(max_window,params.window_size);frames+=1;checksums+=bool(params.has_checksum)
            # In tested 0.25.0 C/CFFI bindings this maps directly to the byte-valued
            # ZSTD_DCtx_setMaxWindowSize; explicit header checks avoid doc-unit ambiguity.
            obj=zstandard.ZstdDecompressor(max_window_size=MAX_WINDOW_BYTES).decompressobj(write_size=BLOCK_BYTES)
            account(obj.decompress(header))
            while True:
                wire=_read(file,3);bits=int.from_bytes(wire,'little');last=bool(bits&1);kind=(bits>>1)&3;length=bits>>3
                if kind==3:raise FrameIntegrityError('reserved Zstd block type')
                if length>min(BLOCK_BYTES,params.window_size):raise FrameIntegrityError('Zstd block exceeds frame/window bound')
                payload=_read(file,1 if kind==1 else length);blocks+=1
                account(obj.decompress(wire+payload))
                if last:break
                if obj.eof or obj.unused_data:raise FrameIntegrityError('premature Zstd frame end')
            if params.has_checksum:account(obj.decompress(_read(file,4)))
            if not obj.eof or obj.unused_data:raise FrameIntegrityError('incomplete or extra Zstd frame data')
            obj=None
        if not frames:raise FrameIntegrityError('Zstd source contains no data frame')
    except zstandard.ZstdError as error:
        raise FrameIntegrityError('Zstd library integrity failure: '+str(error)) from error
    return {'frames':frames,'skippable_frames':skips,'blocks':blocks,'checksum_frames':checksums,
        'decompressed_bytes':total,'maximum_window_bytes':max_window,'maximum_returned_chunk_bytes':max_chunk,
        'integrity':'complete_standard_framing,library_EOF_and_checksums;bounded_block_feeds'}
